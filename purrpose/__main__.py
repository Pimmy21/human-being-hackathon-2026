import argparse
import html
import json
from pathlib import Path

from .core import Review

HERE = Path(__file__).resolve().parent


def load_scenario(name):
    bundle = json.loads((HERE / 'fixtures' / 'maple.json').read_text(encoding='utf-8'))
    case = bundle['case']
    case['sources']['funding']['facts']['grant_inclusion'] = 'separate' if name == 'complete' else 'unknown'
    if name == 'exhausted':
        case['sources']['funding-update']['facts'] = {}
    return case


def report(results):
    esc = lambda x: html.escape(str(x))
    cards = []
    for name, r in results.items():
        amount = 'Unknown' if r['remaining_minor'] is None else f"CAD {r['remaining_minor']/100:,.2f}"
        rows = ''.join(f"<tr><td>{e['sequence']}</td><td>{esc(e['role'])}</td>"
                       f"<td>{esc(e['action'])}</td><td>{esc(e['reason'])}</td></tr>" for e in r['trace'])
        checks = ''.join(f"<li>{esc(k)}: {'pass' if v else 'not passed'}</li>" for k, v in r['gates'].items())
        gaps = ''.join(f"<li>{esc(g['field'])}: {esc(g['reason'])}. {esc(g['suggested_channel'])}</li>" for g in r['gaps'])
        cards.append(f"<section><h2>{esc(name.title())}</h2><p>{esc(r['organization'])} · Maple · Ottawa</p>"
                     f"<p><strong>{esc(r['disposition'])}</strong> · Remaining: {amount}</p>"
                     f"<p>{esc(r['funding_notice'])}</p><p>Repair rounds: {r['usage']['repair_rounds']}; "
                     f"model calls: 0; external requests: 0.</p><p>Stop: {esc(r['stop_reason'])}</p>"
                     f"<details><summary>Evidence checks and source references</summary><ul>{checks}</ul>"
                     f"<pre>{esc(json.dumps(r['claims'], indent=2))}</pre></details>"
                     f"<h3>Information gaps</h3><ul>{gaps or '<li>No unresolved fixture field gaps.</li>'}</ul>"
                     f"<details><summary>Developer trace — actual code execution</summary><div class='scroll'>"
                     f"<table><thead><tr><th>#</th><th>Role</th><th>Action</th><th>Reason</th></tr></thead>"
                     f"<tbody>{rows}</tbody></table></div></details></section>")
    return """<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Purrpose — offline execution report</title><style>
body{font:16px/1.6 system-ui,sans-serif;margin:0;background:#f6f5f0;color:#22352d}main{max-width:1000px;margin:auto;padding:28px}
section{background:white;padding:24px;margin:22px 0;border:1px solid #cdd8cf;border-radius:14px}h1,h2{line-height:1.2}
.notice{background:#fff0cd;padding:18px;border-radius:10px}summary{cursor:pointer;font-weight:600;padding:12px 0}
.scroll{overflow:auto}table{border-collapse:collapse;width:100%}td,th{padding:10px;text-align:left;border-bottom:1px solid #ddd;vertical-align:top}
pre{white-space:pre-wrap;overflow-wrap:anywhere;font-size:13px}h3{font-size:17px}</style><main>
<h1>Purrpose · evidence changes the next action</h1>
<p class="notice"><strong>Executed offline prototype · synthetic evidence only.</strong>
These results were generated by Python, not a model. No real rescue, live source, NVIDIA, Nightshift, Zetaris or H-MEM integration is claimed.
The fixture clock is 24 October 2026. This is a saved report, not a live application or donation page.</p>
<p>Compare three cases below. Only unresolved grant inclusion triggers dispute resolution. Missing information stays unknown.</p>
""" + ''.join(cards) + '</main></html>'


def main():
    p = argparse.ArgumentParser(description='Run synthetic adaptive evidence checks without network or API keys')
    p.add_argument('--scenario', choices=['all', 'complete', 'repair', 'exhausted'], default='all')
    p.add_argument('--output', type=Path, default=HERE / 'artifacts')
    args = p.parse_args()
    names = ['complete', 'repair', 'exhausted'] if args.scenario == 'all' else [args.scenario]
    results = {n: Review(load_scenario(n)).run() for n in names}
    args.output.mkdir(parents=True, exist_ok=True)
    (args.output / 'runs.json').write_text(json.dumps(results, indent=2) + '\n', encoding='utf-8')
    (args.output / 'index.html').write_text(report(results), encoding='utf-8')
    for name, r in results.items():
        print(f"{name}: {r['disposition']}; remaining_minor={r['remaining_minor']}; "
              f"repairs={r['usage']['repair_rounds']}; external_requests=0")
    print(f"Report: {(args.output / 'index.html').resolve()}")


if __name__ == '__main__':
    main()
